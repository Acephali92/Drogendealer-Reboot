/** Deterministischer Hash → Farbton (0–359), damit Grafiken pro Stadt/Spieler stabil bleiben. */
export function hashHue(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h) % 360;
}

/** Kleiner deterministischer Zufallsgenerator aus einem String. */
export function seededRandom(seed: string) {
  let t = hashHue(seed) * 7919 + seed.length;
  return () => {
    t = (t + 0x6d2b79f5) | 0;
    let r = Math.imul(t ^ (t >>> 15), t | 1);
    r ^= r + Math.imul(r ^ (r >>> 7), r | 61);
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}
